const localeNames = ['en', 'zh', 'zh-TW', 'fr', 'ja', 'ru', 'vi']

function placeholders(value) {
  return [...value.matchAll(/{{\s*[^{}]+?\s*}}/g)]
    .map(([placeholder]) => placeholder)
    .sort()
}

function validateTranslations() {
  const keys = new Set()

  for (const entry of translations) {
    if (keys.has(entry.key)) {
      throw new Error(`Duplicate translation key: ${entry.key}`)
    }
    keys.add(entry.key)

    const expectedPlaceholders = JSON.stringify(placeholders(entry.en))
    for (const locale of localeNames) {
      const value = entry[locale]
      if (typeof value !== 'string' || value.length === 0) {
        throw new Error(`Missing ${locale} translation: ${entry.key}`)
      }
      if (JSON.stringify(placeholders(value)) !== expectedPlaceholders) {
        throw new Error(`Placeholder mismatch in ${locale}: ${entry.key}`)
      }
    }
  }
}

