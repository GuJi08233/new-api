// ApplyUpstreamBodyMetadata 补齐包装请求体的长度和独立重放能力。
// 元数据来自当前 body，不能沿用共享 RelayInfo 中上一轮请求体的长度。
func ApplyUpstreamBodyMetadata(req *http.Request, body io.Reader) {
	if encoded, ok := body.(interface{ ContentEncoding() string }); ok {
		req.Header.Set("Content-Encoding", encoded.ContentEncoding())
	}
	replayable, ok := body.(common2.ReplayableBody)
	if !ok {
		return
	}
	if _, rawStorage := body.(common2.BodyStorage); rawStorage {
		req.Body = io.NopCloser(body)
	}
	req.ContentLength = replayable.Size()
	if req.GetBody == nil {
		req.GetBody = replayable.NewReader
	}
}

func SetupApiRequestHeader(info *common.RelayInfo, c *gin.Context, req *http.Header) {
	if info.RelayMode == constant.RelayModeAudioTranscription || info.RelayMode == constant.RelayModeAudioTranslation {
		// multipart/form-data
	} else if info.RelayMode == constant.RelayModeRealtime {
		// websocket
	} else {
		req.Set("Content-Type", c.Request.Header.Get("Content-Type"))
		req.Set("Accept", c.Request.Header.Get("Accept"))
		if info.IsStream && c.Request.Header.Get("Accept") == "" && !PassesAllClientHeaders(info, c) {
			req.Set("Accept", "text/event-stream")
		}
	}
}

const clientHeaderPlaceholderPrefix = "{client_header:"

const (
	headerPassthroughAllKey        = "*"
	headerPassthroughRegexPrefix   = "re:"
	headerPassthroughRegexPrefixV2 = "regex:"
)

var passthroughSkipHeaderNamesLower = map[string]struct{}{
	// RFC 7230 hop-by-hop headers.
	"connection":          {},
	"keep-alive":          {},
	"proxy-connection":    {},
	"proxy-authenticate":  {},
	"proxy-authorization": {},
	"te":                  {},
	"trailer":             {},
	"transfer-encoding":   {},
	"upgrade":             {},

	"cookie":  {},
	"cookie2": {},

	// Additional headers that should not be forwarded by name-matching passthrough rules.
	"host":             {},
	"content-length":   {},
	"content-type":     {},
	"content-encoding": {},
	"accept":           {},
	"accept-encoding":  {},
	"expect":           {},

	// Do not passthrough credentials by wildcard/regex.
	"authorization":  {},
	"mj-api-secret":  {},
	"new-api-user":   {},
	"x-api-key":      {},
	"api-key":        {},
	"x-goog-api-key": {},

	// Added by reverse proxies/CDNs in front of the gateway, not by the client.
	"forwarded":           {},
	"x-real-ip":           {},
	"true-client-ip":      {},
	"x-client-ip":         {},
	"x-cluster-client-ip": {},
	"via":                 {},
	"cdn-loop":            {},

	// WebSocket handshake headers are generated by the client/dialer.
	"sec-websocket-key":        {},
	"sec-websocket-version":    {},
	"sec-websocket-extensions": {},
	"sec-websocket-protocol":   {},
}

var headerPassthroughRegexCache sync.Map // map[string]*regexp.Regexp

func getHeaderPassthroughRegex(pattern string) (*regexp.Regexp, error) {
	pattern = strings.TrimSpace(pattern)
	if pattern == "" {
		return nil, errors.New("empty regex pattern")
	}
	// HTTP field names are case-insensitive. Preserve the configured pattern
	// verbatim (notably escapes such as \Q...\E) and apply case-insensitive
	// matching at compile time instead of lowercasing the regex source.
	cacheKey := "(?i)" + pattern
	if v, ok := headerPassthroughRegexCache.Load(cacheKey); ok {
		if re, ok := v.(*regexp.Regexp); ok {
			return re, nil
		}
		headerPassthroughRegexCache.Delete(cacheKey)
	}
	compiled, err := regexp.Compile(cacheKey)
	if err != nil {
		return nil, err
	}
	actual, _ := headerPassthroughRegexCache.LoadOrStore(cacheKey, compiled)
	if re, ok := actual.(*regexp.Regexp); ok {
		return re, nil
	}
	return compiled, nil
}

func IsHeaderPassthroughRuleKey(key string) bool {
	return isHeaderPassthroughRuleKey(key)
}
func isHeaderPassthroughRuleKey(key string) bool {
	key = strings.TrimSpace(key)
	if key == "" {
		return false
	}
	if key == headerPassthroughAllKey {
		return true
	}
	lower := strings.ToLower(key)
	return strings.HasPrefix(lower, headerPassthroughRegexPrefix) || strings.HasPrefix(lower, headerPassthroughRegexPrefixV2)
}

func shouldSkipPassthroughHeader(name string) bool {
	name = strings.TrimSpace(name)
	if name == "" {
		return true
	}
	lower := strings.ToLower(name)
	if _, ok := passthroughSkipHeaderNamesLower[lower]; ok {
		return true
	}
	// All Sec-WebSocket-* fields are owned by the WebSocket client/server
	// handshake. Forwarding an unfamiliar field can still alter that handshake.
	if strings.HasPrefix(lower, "sec-websocket-") {
		return true
	}
	// Proxy/CDN metadata (X-Forwarded-For, CF-Connecting-IP, CF-Ray, ...)
	// describes the hop into the gateway; forwarding it would leak the client
	// IP and make the upstream request differ from a direct client request.
	if strings.HasPrefix(lower, "x-forwarded-") || strings.HasPrefix(lower, "cf-") {
		return true
	}
	return false
}

// PassesAllClientHeaders reports whether the "*" header passthrough rule is in
// effect (global or channel switch, or a "*" key in the header override).
func PassesAllClientHeaders(info *common.RelayInfo, c *gin.Context) bool {
	if info == nil || info.IsChannelTest || c == nil || c.Request == nil {
		return false
	}
	if model_setting.GetGlobalSettings().PassThroughHeadersEnabled ||
		(info.ChannelMeta != nil && info.ChannelSetting.PassThroughHeadersEnabled) {
		return true
	}
	for k := range common.GetEffectiveHeaderOverride(info) {
		if strings.TrimSpace(k) == headerPassthroughAllKey {
			return true
		}
	}
	return false
}

func applyHeaderOverridePlaceholders(template string, c *gin.Context, apiKey string) (string, bool, error) {
	trimmed := strings.TrimSpace(template)
	if strings.HasPrefix(trimmed, clientHeaderPlaceholderPrefix) {
		afterPrefix := trimmed[len(clientHeaderPlaceholderPrefix):]
		end := strings.Index(afterPrefix, "}")
		if end < 0 || end != len(afterPrefix)-1 {
			return "", false, fmt.Errorf("client_header placeholder must be the full value: %q", template)
		}

		name := strings.TrimSpace(afterPrefix[:end])
		if name == "" {
			return "", false, fmt.Errorf("client_header placeholder name is empty: %q", template)
		}
		if c == nil || c.Request == nil {
			return "", false, fmt.Errorf("missing request context for client_header placeholder")
		}
		clientHeaderValue := c.Request.Header.Get(name)
		if strings.TrimSpace(clientHeaderValue) == "" {
			return "", false, nil
		}
		// Do not interpolate {api_key} inside client-supplied content.
		return clientHeaderValue, true, nil
	}

	if strings.Contains(template, "{api_key}") {
		template = strings.ReplaceAll(template, "{api_key}", apiKey)
	}
	if strings.TrimSpace(template) == "" {
		return "", false, nil
	}
	return template, true, nil
}

// processHeaderOverride applies channel header overrides, with placeholder substitution.
// Supported placeholders:
//   - {api_key}: resolved to the channel API key
//   - {client_header:<name>}: resolved to the incoming request header value
//
// Header passthrough rules (keys only; values are ignored):
//   - "*": passthrough all incoming headers by name (excluding unsafe headers)
//   - "re:<regex>" / "regex:<regex>": passthrough headers whose names match the regex (Go regexp)
//
// Passthrough rules are applied first, then normal overrides are applied, so explicit overrides win.
func processHeaderOverride(info *common.RelayInfo, c *gin.Context) (map[string]string, error) {
	headerValues, err := resolveHeaderOverrideValues(info, c)
	if err != nil {
		return nil, err
	}
	headerOverride := make(map[string]string, len(headerValues))
	for key, values := range headerValues {
		headerOverride[key] = strings.Join(values, ", ")
	}
	return headerOverride, nil
}

// resolveHeaderOverrideValues keeps every field line of passthrough headers so
// repeated client headers reach the upstream exactly as the client sent them.
func resolveHeaderOverrideValues(info *common.RelayInfo, c *gin.Context) (map[string][]string, error) {
	headerOverride := make(map[string][]string)
	if info == nil {
		return headerOverride, nil
	}

	headerOverrideSource := common.GetEffectiveHeaderOverride(info)
	// Background task polling has no client request from which to copy headers.
	hasClientRequest := !info.IsChannelTest && c != nil && c.Request != nil

	passAll := PassesAllClientHeaders(info, c)
	passBody := model_setting.GetGlobalSettings().PassThroughRequestEnabled ||
		(info.ChannelMeta != nil && info.ChannelSetting.PassThroughBodyEnabled)
	var passthroughRegex []*regexp.Regexp
	if hasClientRequest {
		for k := range headerOverrideSource {
			rawKey := strings.TrimSpace(k)
			key := strings.ToLower(rawKey)
			if key == "" {
				continue
			}
			if key == headerPassthroughAllKey {
				passAll = true
				continue
			}

			var pattern string
			switch {
			case strings.HasPrefix(key, headerPassthroughRegexPrefix):
				pattern = strings.TrimSpace(rawKey[len(headerPassthroughRegexPrefix):])
			case strings.HasPrefix(key, headerPassthroughRegexPrefixV2):
				pattern = strings.TrimSpace(rawKey[len(headerPassthroughRegexPrefixV2):])
			default:
				continue
			}

			if pattern == "" {
				return nil, types.NewError(fmt.Errorf("header passthrough regex pattern is empty: %q", k), types.ErrorCodeChannelHeaderOverrideInvalid)
			}
			compiled, err := getHeaderPassthroughRegex(pattern)
			if err != nil {
				return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
			}
			passthroughRegex = append(passthroughRegex, compiled)
		}
	}

	if passAll || len(passthroughRegex) > 0 {
		connectionHeaderNames := make(map[string]struct{})
		for _, value := range c.Request.Header.Values("Connection") {
			for _, name := range strings.Split(value, ",") {
				name = strings.ToLower(strings.TrimSpace(name))
				if name != "" {
					connectionHeaderNames[name] = struct{}{}
				}
			}
		}
		for name := range c.Request.Header {
			lowerName := strings.ToLower(strings.TrimSpace(name))
			clientEntityHeader := passAll && (lowerName == "accept" || lowerName == "accept-encoding" ||
				(lowerName == "content-type" && passBody))
			if shouldSkipPassthroughHeader(name) && !clientEntityHeader {
				continue
			}
			if _, declaredHopByHop := connectionHeaderNames[strings.ToLower(strings.TrimSpace(name))]; declaredHopByHop {
				continue
			}
			if !passAll {
				matched := false
				for _, re := range passthroughRegex {
					if re.MatchString(name) {
						matched = true
						break
					}
				}
				if !matched {
					continue
				}
			}
			headerOverride[lowerName] = slices.Clone(c.Request.Header.Values(name))
		}
	}

	for k, v := range headerOverrideSource {
		if isHeaderPassthroughRuleKey(k) {
			continue
		}
		key := strings.TrimSpace(strings.ToLower(k))
		if key == "" {
			continue
		}

		str, ok := v.(string)
		if !ok {
			return nil, types.NewError(nil, types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		// Channel tests and background task polling have no client request to
		// read client_header placeholders from, so those overrides are skipped.
		if !hasClientRequest && strings.HasPrefix(strings.TrimSpace(str), clientHeaderPlaceholderPrefix) {
			continue
		}

		value, include, err := applyHeaderOverridePlaceholders(str, c, info.ApiKey)
		if err != nil {
			return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		if !include {
			continue
		}

		headerOverride[key] = []string{value}
	}
	return headerOverride, nil
}

func ResolveHeaderOverride(info *common.RelayInfo, c *gin.Context) (map[string]string, error) {
	return processHeaderOverride(info, c)
}

// ResolveHeaderOverrideValues preserves repeated fields for SDK/signing paths.
func ResolveHeaderOverrideValues(info *common.RelayInfo, c *gin.Context) (http.Header, error) {
	values, err := resolveHeaderOverrideValues(info, c)
	if err != nil {
		return nil, err
	}
	headers := make(http.Header, len(values))
	applyHeaderOverrideValues(headers, nil, values)
	return headers, nil
}

func applyHeaderOverrideValues(header http.Header, req *http.Request, headerOverride map[string][]string) {
	for key, values := range headerOverride {
		header[http.CanonicalHeaderKey(key)] = slices.Clone(values)
		if req != nil && strings.EqualFold(key, "Host") && len(values) > 0 {
			req.Host = values[0]
		}
	}
}

// ApplyHeaderOverride applies channel overrides after the adaptor's headers.
// Without a client request, passthrough rules are skipped.
func ApplyHeaderOverride(info *common.RelayInfo, c *gin.Context, req *http.Request) error {
	return ApplyHeaderOverrideToRequest(info, c, req)
}

func ApplyHeaderOverrideToRequest(info *common.RelayInfo, c *gin.Context, req *http.Request) error {
	headerOverride, err := resolveHeaderOverrideValues(info, c)
	if err != nil {
		return err
	}
	if req != nil {
		if req.Header == nil {
			req.Header = make(http.Header)
		}
		if PassesAllClientHeaders(info, c) {
			passBody := model_setting.GetGlobalSettings().PassThroughRequestEnabled ||
				(info.ChannelMeta != nil && info.ChannelSetting.PassThroughBodyEnabled)
			for name := range req.Header {
				// Keep provider credentials/signing fields and entity metadata for
				// converted bodies. Everything else must come from the client or
				// an explicit channel override, not adaptor defaults.
				lower := strings.ToLower(name)
				switch lower {
				case "authorization", "x-api-key", "api-key", "x-goog-api-key", "mj-api-secret",
					"sec-websocket-protocol":
					continue
				case "content-encoding":
					if original := c.GetString(common2.KeyOriginalContentEncoding); passBody && original != "" && req.Header.Get(name) == original {
						continue
					}
					if !passBody {
						continue
					}
				case "content-type":
					if !passBody {
						continue
					}
				}
				if strings.HasPrefix(lower, "x-amz-") || strings.HasPrefix(lower, "x-tc-") {
					continue
				}
				delete(req.Header, name)
			}
		}
		applyHeaderOverrideValues(req.Header, req, headerOverride)
	}
	// net/http sends "Go-http-client/1.1" when User-Agent is absent; an
	// explicitly empty value suppresses it so a client without a UA stays without one.
	if req == nil {
		return nil
	}
	if _, hasUA := req.Header["User-Agent"]; !hasUA && PassesAllClientHeaders(info, c) &&
		c.Request.Header.Get("User-Agent") == "" {
		req.Header["User-Agent"] = []string{""}
	}
	return nil
}

func DoApiRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	logger.LogDebug(c, "fullRequestURL: %s", common.SanitizeURLForLog(fullRequestURL))
	req, err := http.NewRequestWithContext(c.Request.Context(), c.Request.Method, fullRequestURL, requestBody)
	if err != nil {
		return nil, fmt.Errorf("new request failed: %w", err)
	}
	ApplyUpstreamBodyMetadata(req, requestBody)
	headers := req.Header
	err = a.SetupRequestHeader(c, &headers, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	resp, err := doRequest(c, req, info)
	if err != nil {
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	return resp, nil
}

func DoFormRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	logger.LogDebug(c, "fullRequestURL: %s", common.SanitizeURLForLog(fullRequestURL))
	req, err := http.NewRequestWithContext(c.Request.Context(), c.Request.Method, fullRequestURL, requestBody)
	if err != nil {
		return nil, fmt.Errorf("new request failed: %w", err)
	}
	ApplyUpstreamBodyMetadata(req, requestBody)
	// set form data
	req.Header.Set("Content-Type", c.Request.Header.Get("Content-Type"))
	headers := req.Header
	err = a.SetupRequestHeader(c, &headers, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	resp, err := doRequest(c, req, info)
	if err != nil {
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	return resp, nil
}

func DoWssRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*websocket.Conn, error) {
	helper.ResetUpstreamResponseHeaders(c)
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	targetHeader := http.Header{}
	err = a.SetupRequestHeader(c, &targetHeader, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	// 在 SetupRequestHeader 之后应用 Header Override，确保用户设置优先级最高
	// 这样可以覆盖默认的 Authorization header 设置
	prepared := &http.Request{Header: targetHeader}
	if err := ApplyHeaderOverrideToRequest(info, c, prepared); err != nil {
		return nil, err
	}
	requestCtx := context.Background()
	if c != nil && c.Request != nil {
		requestCtx = c.Request.Context()
	}
	targetConn, handshakeResp, err := websocket.DefaultDialer.DialContext(requestCtx, fullRequestURL, targetHeader)
	if handshakeResp != nil && info != nil && info.ChannelMeta != nil && info.ChannelSetting.PassThroughHeadersEnabled {
		helper.CopyUpstreamResponseHeaders(c, handshakeResp)
	}
	if handshakeResp != nil && handshakeResp.Body != nil {
		_ = handshakeResp.Body.Close()
	}
	if err != nil {
		return nil, fmt.Errorf("dial failed to %s: %w", common.SanitizeURLForLog(fullRequestURL), err)
	}
	// send request body
	//all, err := io.ReadAll(requestBody)
	//err = service.WssString(c, targetConn, string(all))
	return targetConn, nil
}

type cancelResponseBody struct {
	io.ReadCloser
	cancel context.CancelFunc
}

func (body *cancelResponseBody) Close() error {
	defer body.cancel()
	return body.ReadCloser.Close()
}

func DoRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	return doRequest(c, req, info)
}

// DoPreparedRequest sends a request whose final headers (and any signature)
// have already been prepared. It intentionally does not resolve or reapply
// channel header overrides at the transport boundary.
func DoPreparedRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	return doPreparedRequest(c, req, info)
}

func doRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	return doRequestWithPreparedHeaders(c, req, info, false)
}

func doPreparedRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	return doRequestWithPreparedHeaders(c, req, info, true)
}

func keepUpstreamRedirectResponse(_ *http.Request, _ []*http.Request) error {
	return http.ErrUseLastResponse
}

func doRequestWithPreparedHeaders(c *gin.Context, req *http.Request, info *common.RelayInfo, headersPrepared bool) (*http.Response, error) {
	// A retry reuses the Gin context; remove metadata from the previous
	// upstream attempt before preparing the next response.
	helper.ResetUpstreamResponseHeaders(c)

	if !headersPrepared {
		// Apply overrides at the shared HTTP boundary so custom adaptors and task
		// adaptors receive the same passthrough behavior as DoApiRequest/DoFormRequest.
		if err := ApplyHeaderOverrideToRequest(info, c, req); err != nil {
			return nil, err
		}
	}

	var client *http.Client
	var err error
	if info.ChannelSetting.Proxy != "" || info.ChannelSetting.DisableKeepAlive || PassesAllClientHeaders(info, c) {
		client, err = service.NewProxyHttpClientOptions(info.ChannelSetting.Proxy, service.ProxyClientOptions{
			DisableKeepAlive:   info.ChannelSetting.DisableKeepAlive,
			DisableCompression: PassesAllClientHeaders(info, c),
		})
		if err != nil {
			return nil, fmt.Errorf("new proxy http client failed: %w", err)
		}
	} else {
		client = service.GetHttpClient()
	}
	// 客户端和连接池是共享的，只在本次relay副本上禁止3xx自动重发凭据/请求体。
	relayClient := *client
	relayClient.CheckRedirect = keepUpstreamRedirectResponse

	var cancelUpstream context.CancelFunc
	if info.IsStream {
		helper.SetEventStreamHeaders(c)
		generalSettings := operation_setting.GetGeneralSetting()
		channelResponsePassthrough := info.ChannelMeta != nil && info.ChannelSetting.PassThroughHeadersEnabled
		if generalSettings.PingIntervalEnabled && !info.DisablePing && !channelResponsePassthrough {
			var upstreamCtx context.Context
			upstreamCtx, cancelUpstream = context.WithCancel(req.Context())
			req = req.WithContext(upstreamCtx)
			stopPinger := helper.StartStreamKeepAlive(c, time.Duration(generalSettings.PingIntervalSeconds)*time.Second, cancelUpstream)
			defer stopPinger()
		} else {
			// Header passthrough must not commit downstream headers before the
			// final upstream response metadata is available.
			helper.StopStreamKeepAlive(c)
		}
	}

	resp, err := relayClient.Do(req)
	if err != nil {
		if cancelUpstream != nil {
			cancelUpstream()
		}
		logger.LogError(c, "do request failed: "+err.Error())
		return nil, types.NewError(err, types.ErrorCodeDoRequestFailed, types.ErrOptionWithHideErrMsg("upstream error: do request failed"))
	}
	if resp == nil {
		if cancelUpstream != nil {
			cancelUpstream()
		}
		return nil, errors.New("resp is nil")
	}
	if PassesAllClientHeaders(info, c) {
		if err := decodeUpstreamResponse(resp); err != nil {
			_ = resp.Body.Close()
			if cancelUpstream != nil {
				cancelUpstream()
			}
			return nil, fmt.Errorf("decode upstream response failed: %w", err)
		}
	}
	if cancelUpstream != nil {
		resp.Body = &cancelResponseBody{ReadCloser: resp.Body, cancel: cancelUpstream}
	}
	if resp.StatusCode >= http.StatusOK && resp.StatusCode < http.StatusMultipleChoices {
		helper.StopStreamKeepAlive(c)
	}

	if upID := resp.Header.Get(common2.RequestIdKey); upID != "" {
		c.Set(common2.UpstreamRequestIdKey, upID)
	}
	// Copy body-independent metadata at the shared boundary. Representation
	// headers are deliberately left for the response handler, which knows
	// whether it forwards the original entity or writes a transformed one.
	// Doing this before returning also covers custom handlers that write their
	// response directly instead of using the shared body copier.
	if info.ChannelMeta != nil && info.ChannelSetting.PassThroughHeadersEnabled {
		helper.CopyUpstreamResponseHeaders(c, resp)
	}

	if req.Body != nil {
		_ = req.Body.Close()
	}
	if c != nil && c.Request != nil && c.Request.Body != nil {
		_ = c.Request.Body.Close()
	}
	return resp, nil
}

func DoTaskApiRequest(a TaskAdaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	return doTaskApiRequest(a, c, info, requestBody, false)
}

func DoPreparedTaskApiRequest(a TaskAdaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	return doTaskApiRequest(a, c, info, requestBody, true)
}

func doTaskApiRequest(a TaskAdaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader, headersPrepared bool) (*http.Response, error) {
	fullRequestURL, err := a.BuildRequestURL(info)
	if err != nil {
		return nil, err
	}
	req, err := http.NewRequestWithContext(c.Request.Context(), c.Request.Method, fullRequestURL, requestBody)
	if err != nil {
		return nil, fmt.Errorf("new request failed: %w", err)
	}
	ApplyUpstreamBodyMetadata(req, requestBody)

	err = a.BuildRequestHeader(c, req, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	var resp *http.Response
	if headersPrepared {
		resp, err = doPreparedRequest(c, req, info)
	} else {
		resp, err = doRequest(c, req, info)
	}
	if err != nil {
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	return resp, nil
}
